ALTER TABLE equipment ADD COLUMN IF NOT EXISTS shareable BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS sharing_listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id BIGINT NOT NULL UNIQUE REFERENCES equipment(id) ON DELETE CASCADE,
    fee_per_hour NUMERIC(12,2) NOT NULL CHECK (fee_per_hour >= 0),
    external_share_percentage NUMERIC(5,2) NOT NULL CHECK (external_share_percentage BETWEEN 0 AND 100),
    minimum_notice_hours INTEGER NOT NULL DEFAULT 0 CHECK (minimum_notice_hours >= 0),
    maximum_booking_hours INTEGER NOT NULL CHECK (maximum_booking_hours > 0),
    terms VARCHAR(2000) NOT NULL DEFAULT '',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sharing_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id BIGINT NOT NULL REFERENCES equipment(id),
    requester_id BIGINT NOT NULL REFERENCES users(id),
    requester_institution_id BIGINT NOT NULL REFERENCES institutions(id),
    purpose VARCHAR(500) NOT NULL,
    start_date TIMESTAMP NOT NULL,
    end_date TIMESTAMP NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    requester_reviewed_by BIGINT REFERENCES users(id),
    requester_reviewed_at TIMESTAMP,
    requester_review_remarks VARCHAR(500),
    reviewed_by BIGINT REFERENCES users(id),
    reviewed_at TIMESTAMP,
    review_remarks VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_sharing_request_dates CHECK (end_date > start_date)
);
CREATE INDEX IF NOT EXISTS ix_sharing_requests_requester ON sharing_requests(requester_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_sharing_requests_owner_queue ON sharing_requests(equipment_id, status);

CREATE TABLE IF NOT EXISTS sharing_agreements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id BIGINT NOT NULL REFERENCES equipment(id),
    owner_institution_id BIGINT NOT NULL REFERENCES institutions(id),
    partner_institution_id BIGINT NOT NULL REFERENCES institutions(id),
    request_id BIGINT NOT NULL UNIQUE REFERENCES sharing_requests(id),
    start_date TIMESTAMP NOT NULL,
    end_date TIMESTAMP NOT NULL,
    allowed_start_time TIME,
    allowed_end_time TIME,
    fee_per_hour NUMERIC(12,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    approved_by BIGINT NOT NULL REFERENCES users(id),
    approved_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_by BIGINT REFERENCES users(id),
    revoked_at TIMESTAMP,
    revocation_reason VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS sharing_access_grants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agreement_id BIGINT NOT NULL REFERENCES sharing_agreements(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    revoked_by BIGINT REFERENCES users(id),
    revoked_at TIMESTAMP,
    revocation_reason VARCHAR(500),
    CONSTRAINT uk_sharing_grant_user UNIQUE (agreement_id, user_id)
);

ALTER TABLE bookings ADD COLUMN IF NOT EXISTS sharing_agreement_id BIGINT REFERENCES sharing_agreements(id);
