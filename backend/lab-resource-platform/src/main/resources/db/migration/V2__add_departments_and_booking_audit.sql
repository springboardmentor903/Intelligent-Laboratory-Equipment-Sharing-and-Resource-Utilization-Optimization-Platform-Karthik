-- Milestone 1 Additive Migration
-- Adds departments, department associations on users and equipment, and booking audit logging

CREATE TABLE IF NOT EXISTS departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_departments_institution_name UNIQUE (institution_id, name),
    CONSTRAINT fk_departments_institution FOREIGN KEY (institution_id) REFERENCES institutions(id) ON DELETE RESTRICT
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS department_id BIGINT NULL;
ALTER TABLE equipment ADD COLUMN IF NOT EXISTS department_id BIGINT NULL;

CREATE TABLE IF NOT EXISTS booking_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    event_type VARCHAR(40) NOT NULL,
    previous_status VARCHAR(30),
    new_status VARCHAR(30),
    actor_email VARCHAR(180),
    occurred_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_booking_audit_booking FOREIGN KEY (booking_id) REFERENCES bookings(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_departments_institution_id ON departments(institution_id);
CREATE INDEX IF NOT EXISTS ix_users_department_id ON users(department_id);
CREATE INDEX IF NOT EXISTS ix_equipment_department_id ON equipment(department_id);
CREATE INDEX IF NOT EXISTS ix_booking_audit_booking_id ON booking_audit_logs(booking_id);
CREATE INDEX IF NOT EXISTS ix_booking_audit_occurred_at ON booking_audit_logs(occurred_at);
