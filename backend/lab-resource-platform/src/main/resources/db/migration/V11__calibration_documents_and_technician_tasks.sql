-- Milestone 3 Session 2: Calibration Tracking, Document Storage & Technician Tasks

-- 1. Stored documents table for certificates, equipment manuals, and maintenance reports
CREATE TABLE IF NOT EXISTS stored_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(50) NOT NULL, -- 'CALIBRATION_CERTIFICATE', 'EQUIPMENT_MANUAL', 'MAINTENANCE_REPORT'
    entity_id BIGINT,                  -- equipment_id, calibration_record_id, work_order_id
    file_name VARCHAR(255) NOT NULL,
    file_type VARCHAR(100) NOT NULL,   -- 'application/pdf', 'image/png', 'image/jpeg'
    file_size BIGINT NOT NULL,
    file_reference VARCHAR(500) NOT NULL,
    uploaded_by BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_stored_docs_entity ON stored_documents(entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_stored_docs_ref ON stored_documents(file_reference);
CREATE INDEX IF NOT EXISTS idx_stored_docs_uploader ON stored_documents(uploaded_by);

-- 2. Link calibration records to stored documents and originating work order
ALTER TABLE calibration_records ADD COLUMN IF NOT EXISTS certificate_document_id BIGINT;
ALTER TABLE calibration_records ADD COLUMN IF NOT EXISTS certificate_reference VARCHAR(500);
ALTER TABLE calibration_records ADD COLUMN IF NOT EXISTS work_order_id BIGINT;

CREATE INDEX IF NOT EXISTS idx_calibration_wo ON calibration_records(work_order_id);
CREATE INDEX IF NOT EXISTS idx_calibration_doc ON calibration_records(certificate_document_id);

-- 3. Link work orders to calibration records and report documents
ALTER TABLE work_orders ADD COLUMN IF NOT EXISTS report_document_id BIGINT;
ALTER TABLE work_orders ADD COLUMN IF NOT EXISTS report_reference VARCHAR(500);
ALTER TABLE work_orders ADD COLUMN IF NOT EXISTS calibration_record_id BIGINT;

CREATE INDEX IF NOT EXISTS idx_wo_cal_record ON work_orders(calibration_record_id);
CREATE INDEX IF NOT EXISTS idx_wo_report_doc ON work_orders(report_document_id);
CREATE INDEX IF NOT EXISTS idx_wo_assigned_status_sched ON work_orders(assigned_to, status, scheduled_date);
