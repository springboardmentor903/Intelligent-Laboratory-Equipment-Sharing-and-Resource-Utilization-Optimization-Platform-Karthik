-- Milestone 3 Session 3: Usage Costs, Department Allocation, Budgets, Invoices & Billing

-- 1. Add optional default hourly_rate to equipment
ALTER TABLE equipment ADD COLUMN IF NOT EXISTS hourly_rate NUMERIC(12, 2) DEFAULT 0.00;

-- 2. Usage charges table
CREATE TABLE IF NOT EXISTS usage_charges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    equipment_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    institution_id BIGINT NOT NULL,           -- Owner institution of equipment
    user_institution_id BIGINT,                -- User's home institution (null if UNASSIGNED)
    department_id BIGINT,                      -- User's department (null if unassigned or no department)
    charge_type VARCHAR(30) NOT NULL,          -- 'INTERNAL', 'EXTERNAL', 'UNASSIGNED'
    hourly_rate NUMERIC(12, 2) NOT NULL,       -- Snapshot of rate at time of charge
    usage_minutes BIGINT NOT NULL,             -- Actual usage minutes
    amount NUMERIC(12, 2) NOT NULL,            -- (usage_minutes * hourly_rate) / 60, HALF_UP
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING', -- 'PENDING', 'INVOICED', 'PAID', 'CANCELLED'
    invoice_id BIGINT,                         -- Linked invoice when invoiced
    sharing_agreement_id BIGINT,               -- If charged under a sharing agreement
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usage_charges_booking UNIQUE (booking_id)
);

CREATE INDEX IF NOT EXISTS idx_usage_charges_inst_status ON usage_charges(institution_id, status);
CREATE INDEX IF NOT EXISTS idx_usage_charges_user ON usage_charges(user_id);
CREATE INDEX IF NOT EXISTS idx_usage_charges_dept ON usage_charges(department_id);
CREATE INDEX IF NOT EXISTS idx_usage_charges_equip ON usage_charges(equipment_id);
CREATE INDEX IF NOT EXISTS idx_usage_charges_invoice ON usage_charges(invoice_id);
CREATE INDEX IF NOT EXISTS idx_usage_charges_created ON usage_charges(created_at);

-- 3. Department budgets table
CREATE TABLE IF NOT EXISTS department_budgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    fiscal_year INTEGER NOT NULL,
    allocated_amount NUMERIC(14, 2) NOT NULL DEFAULT 0.00 CHECK (allocated_amount >= 0),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_dept_budget_dept_year UNIQUE (department_id, fiscal_year)
);

CREATE INDEX IF NOT EXISTS idx_dept_budgets_inst_year ON department_budgets(institution_id, fiscal_year);
CREATE INDEX IF NOT EXISTS idx_dept_budgets_dept ON department_budgets(department_id);

-- 4. Sequence for unique invoice number generation
CREATE SEQUENCE IF NOT EXISTS invoice_number_seq START WITH 1;

-- 5. Invoices table
CREATE TABLE IF NOT EXISTS invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number VARCHAR(50) NOT NULL UNIQUE, -- 'INV-YYYY-XXXXXX'
    institution_id BIGINT NOT NULL,             -- Issuer institution
    recipient_institution_id BIGINT,            -- For EXTERNAL inter-institution invoices
    recipient_department_id BIGINT,             -- For INTERNAL department chargeback invoices
    invoice_type VARCHAR(30) NOT NULL,          -- 'INTER_INSTITUTION', 'DEPARTMENT_CHARGEBACK'
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    subtotal NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    tax_rate NUMERIC(5, 2) NOT NULL DEFAULT 0.00,
    tax_amount NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    total_amount NUMERIC(14, 2) NOT NULL DEFAULT 0.00,
    due_date DATE NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'DRAFT', -- 'DRAFT', 'ISSUED', 'PAID', 'CANCELLED'
    issued_at TIMESTAMP,
    paid_at TIMESTAMP,
    cancelled_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_invoices_inst_status ON invoices(institution_id, status);
CREATE INDEX IF NOT EXISTS idx_invoices_recipient_inst ON invoices(recipient_institution_id);
CREATE INDEX IF NOT EXISTS idx_invoices_recipient_dept ON invoices(recipient_department_id);
CREATE INDEX IF NOT EXISTS idx_invoices_due_date ON invoices(due_date);
CREATE INDEX IF NOT EXISTS idx_invoices_created ON invoices(created_at);

-- 6. Invoice items (itemized charges snapshot)
CREATE TABLE IF NOT EXISTS invoice_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL,
    charge_id BIGINT,
    equipment_id BIGINT NOT NULL,
    equipment_name VARCHAR(150),
    user_id BIGINT NOT NULL,
    user_name VARCHAR(150),
    usage_minutes BIGINT NOT NULL,
    hourly_rate NUMERIC(12, 2) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_invoice_items_invoice FOREIGN KEY (invoice_id) REFERENCES invoices(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_invoice_items_invoice ON invoice_items(invoice_id);
CREATE INDEX IF NOT EXISTS idx_invoice_items_charge ON invoice_items(charge_id);
